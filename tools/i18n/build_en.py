#!/usr/bin/env python3
"""Builds res://i18n/en.gd (the English table) from tools/i18n/en_*.py and checks it against the code.

Every Korean string literal in ui/ and platform/input_mode_manager.gd is a translation key (ui/i18n.gd). This script
 1. collects those literals,
 2. reports keys with no English (they would show in Korean in the English game),
 3. checks that every translation keeps the same %-placeholders and {blanks} as its key,
 4. writes i18n/en.gd.
Run: python3 tools/i18n/build_en.py      (exit 1 when a key is missing or a placeholder does not match)
"""
import glob, os, re, sys, importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))
# not shown to players (diagnostic log) or the language's own name
SKIP_FILES = {"platform/steam_deck_manager.gd"}
SKIP_KEYS = {"한국어", "언어 · Language", "가", "힣"}   # language names stay in their own language; a character range

def code_keys():
    files = sorted(glob.glob(os.path.join(ROOT, "ui", "*.gd")) + glob.glob(os.path.join(ROOT, "ui", "board", "*.gd"))
                   + [os.path.join(ROOT, "platform", "input_mode_manager.gd")])
    lit = re.compile(r'"((?:[^"\\]|\\.)*)"')
    keys = {}
    for f in files:
        rel = os.path.relpath(f, ROOT)
        if rel in SKIP_FILES:
            continue
        for i, line in enumerate(open(f, encoding="utf-8"), 1):
            if line.strip().startswith("#"):
                continue
            for m in lit.finditer(line):
                pre = line[:m.start()]
                if "#" in pre and pre.count('"') % 2 == 0:
                    break
                t = m.group(1)
                if re.search("[가-힣]", t) and t not in SKIP_KEYS:
                    keys.setdefault(t, "%s:%d" % (rel, i))
    return keys

def table():
    tbl = {}
    for p in sorted(glob.glob(os.path.join(HERE, "en_*.py"))):
        spec = importlib.util.spec_from_file_location(os.path.basename(p)[:-3], p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        for k, v in mod.T.items():
            if k in tbl and tbl[k] != v and "polish" not in p:
                print("conflict:", k, "|", tbl[k], "|", v)     # en_zz_polish.py overrides on purpose
            tbl[k] = v
    return tbl

def placeholders(s):
    return sorted(re.findall(r'%[-0-9.]*[sdf]|\{[a-z_]+\}', s.replace("%%", "")))

def main():
    keys = code_keys()
    tbl = table()
    bad = 0
    for k, where in keys.items():
        if k not in tbl:
            print("MISSING  %s  (%s)" % (k, where)); bad += 1
    for k, v in tbl.items():
        if placeholders(k) != placeholders(v):
            print("PLACEHOLDERS  %s  ->  %s" % (k, v)); bad += 1
        if re.search("[가-힣]", v):
            print("HANGUL IN ENGLISH  %s  ->  %s" % (k, v)); bad += 1
    unused = [k for k in tbl if k not in keys]
    for k in unused:
        print("unused (no longer in the code):", k)
    out = ['extends RefCounted', '## English table, generated by tools/i18n/build_en.py from tools/i18n/en_*.py. Do not edit by hand.',
           '## Key = the Korean text in the code (ui/i18n.gd).', '', 'const EN := {']
    for k in sorted(tbl):
        out.append('\t"%s": "%s",' % (k, tbl[k].replace('"', '\\"') if '\\"' not in tbl[k] else tbl[k]))
    out.append('}')
    os.makedirs(os.path.join(ROOT, "i18n"), exist_ok=True)
    open(os.path.join(ROOT, "i18n", "en.gd"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("keys in code: %d, translations: %d, unused: %d, problems: %d" % (len(keys), len(tbl), len(unused), bad))
    sys.exit(1 if bad else 0)

main()
